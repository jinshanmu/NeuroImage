async page => {
  const origin = new URL(page.url()).origin, errors = [], external = [];
  const assert = (ok, message) => { if (!ok) throw Error(message); };
  const onError = error => errors.push(String(error));
  page.on('pageerror', onError);
  await page.unroute('**/*');
  await page.route('**/*', route => new URL(route.request().url()).origin === origin
    ? route.continue() : (external.push(route.request().url()), route.abort()));
  const ready = async () => {
    await page.waitForFunction(() => document.querySelector('.model-status')?.textContent?.startsWith('Ready'), null, {timeout: 120000});
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    assert(!await page.locator('.error[role=alert]').count(), 'The model viewer reported an error.');
  };
  const output = 'data/benchmarks/mug500_source_mesh/installed-browser';
  await page.goto(origin);
  await page.getByRole('combobox', {name: 'Source for Skull base', exact: true}).selectOption('mug500_source_mesh');
  const started = Date.now();
  await page.getByRole('button', {name: 'Browse Skull base', exact: true}).click();
  await ready();
  const loadedSeconds = (Date.now() - started) / 1000;
  const key = await page.getByRole('combobox', {name: 'Source', exact: true}).inputValue();
  const bookKey = 'neuroimage:model-notebook:primary:' + key + ':skull-base-context';
  assert(!await page.evaluate(k => localStorage.getItem(k), bookKey), 'Preserve an existing source notebook before this first-run fixture.');
  await page.getByRole('checkbox', {name: 'Highlight selected', exact: true}).uncheck();
  await page.getByRole('button', {name: 'Full model view', exact: true}).click();
  await ready();
  const canvas = page.getByLabel('Independent native source model', {exact: true});
  const exportView = async name => {
    const event = page.waitForEvent('download');
    await page.getByRole('button', {name: 'Export teaching image', exact: true}).click();
    await (await event).saveAs(output + '/' + name + '.zip');
  };
  await canvas.screenshot({path: output + '/full-model.png'});
  await exportView('full-model');
  await page.getByRole('button', {name: 'Learning tools', exact: true}).click();
  await page.getByRole('textbox', {name: 'Model teaching notes', exact: true}).fill('Original author-cleaned A0101 surface. Source cleanup is documented; no project surface repair or fine foraminal labels.');
  await page.getByRole('button', {name: 'Lessons', exact: true}).click();
  await page.getByRole('combobox', {name: 'Model lesson', exact: true}).selectOption('NI-SKM001');
  await ready();
  await page.getByRole('textbox', {name: 'Model lesson response', exact: true}).fill('The original CT and unprocessed binary sections are distinct from the author-cleaned surface.');
  await page.getByRole('button', {name: 'Compare with source answer', exact: true}).click();
  await page.getByText('My model notebook', {exact: false}).click();
  await page.getByRole('textbox', {name: 'Model notebook title', exact: true}).fill('Author-cleaned skull source observation');
  await page.getByRole('textbox', {name: 'Model notebook prompt', exact: true}).fill('Inspect the whole supplied skull surface and discuss the source-author cleanup.');
  await page.getByRole('button', {name: 'Add current view', exact: true}).click();
  await page.getByRole('button', {name: 'Notes', exact: true}).click();
  await page.getByText('Native XYZ cutaway', {exact: true}).click();
  await page.getByRole('button', {name: 'Cut selected at cursor', exact: true}).click();
  await page.getByLabel('Model cutaway axis', {exact: true}).selectOption('2');
  await page.getByLabel('Model cutaway position', {exact: true}).fill('30');
  await page.locator('.model-tools').getByRole('button', {name: 'Close', exact: true}).click();
  await ready();
  const box = await canvas.boundingBox();
  await page.mouse.move(box.x + box.width * .5, box.y + box.height * .5);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * .5, box.y + box.height * .5 - 140, {steps: 12});
  await page.mouse.up();
  await ready();
  await page.getByRole('button', {name: 'Save scene', exact: true}).click();
  let event = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Export scene', exact: true}).click();
  await (await event).saveAs(output + '/cutaway-scene.json');
  await canvas.screenshot({path: output + '/cutaway-saved.png'});
  await exportView('cutaway');
  await page.getByRole('button', {name: 'Full model view', exact: true}).click();
  await page.getByRole('button', {name: 'Restore saved', exact: true}).click();
  await ready();
  await canvas.screenshot({path: output + '/cutaway-restored.png'});
  await page.getByLabel('Import model scene file', {exact: true}).setInputFiles(output + '/cutaway-scene.json');
  await ready();
  await canvas.screenshot({path: output + '/cutaway-imported.png'});
  await page.getByRole('button', {name: 'Learning tools', exact: true}).click();
  await page.getByRole('button', {name: 'Lessons', exact: true}).click();
  await page.getByText('My model notebook', {exact: false}).click();
  await page.getByRole('textbox', {name: 'Model notebook prompt', exact: true}).fill('Inspect the native display cutaway. It creates no filled cap, new bone boundary or named foraminal label.');
  await page.getByRole('button', {name: 'Add current view', exact: true}).click();
  event = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Export notebook', exact: true}).click();
  await (await event).saveAs(output + '/source-skull-notebook.json');
  await page.getByLabel('Import model notebook file', {exact: true}).setInputFiles(output + '/source-skull-notebook.json');
  const notebook = await page.evaluate(k => JSON.parse(localStorage.getItem(k)), bookKey);
  assert(notebook.scenes.length === 2 && notebook.scenes[1].scene.state.surfaceCutaway.position_mm === 30, 'Native cutaway notebook did not restore.');
  page.off('pageerror', onError);
  await page.unroute('**/*');
  assert(!errors.length && !external.length, errors.concat(external).join('\n'));
  return {status: 'passed', source: key, opening_seconds: loadedSeconds, notebook_views: 2,
    checks: ['Anatomy group source entry', 'Exact source-cleaned surface', 'Whole-model context', 'Native clipping', 'Portable scene and notebook restoration', 'Source-processing lesson', 'Licensed teaching exports'],
    page_errors: errors, external_requests: external};
}
