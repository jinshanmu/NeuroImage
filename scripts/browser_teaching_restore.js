async page => {
  const failures=[];page.on('pageerror',error=>failures.push(String(error)));
  const assert=(condition,message)=>{if(!condition)throw new Error(message);};
  const ready=()=>page.waitForFunction(()=>!document.querySelector('button.primary')?.disabled&&document.querySelector('.live-status')?.textContent?.startsWith('Ready'),null,{timeout:45000});
  await page.reload();await ready();
  const catalog=await page.evaluate(async()=>(await(await fetch('/api/atlases')).json()).atlases);
  const first=catalog.find(a=>a.dataset_id==='spl_nac'),second=catalog.find(a=>a.dataset_id==='cerebra');
  await page.getByRole('combobox',{name:'Local atlas',exact:true}).selectOption(first.key);await ready();
  await page.getByRole('button',{name:'Learn',exact:true}).click();
  await page.getByRole('combobox',{name:'Lesson',exact:true}).selectOption('NI-L004');
  await page.getByRole('button',{name:'Next structure',exact:true}).click();
  await page.getByRole('checkbox',{name:'Identification practice',exact:true}).check();
  const answer='My unfinished identification response.';
  await page.getByRole('textbox',{name:'Identification answer',exact:true}).fill(answer);
  await page.getByRole('button',{name:'Save scene',exact:true}).click();
  await page.waitForFunction(key=>JSON.parse(localStorage.getItem(key)).state.teaching?.step===1,'neuroimage:scene:'+first.key);
  const original=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),'neuroimage:scene:'+first.key);
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export scene',exact:true}).click();
  const path='data/exports/spl_nac/browser-validation/teaching-context-scene.json';await(await download).saveAs(path);
  await page.reload();await ready();
  await page.getByRole('button',{name:'Restore saved',exact:true}).click();await ready();
  const check=async()=>{
    assert(await page.getByRole('combobox',{name:'Lesson',exact:true}).inputValue()==='NI-L004','The restored lesson differs.');
    assert((await page.locator('.lesson-progress').textContent()).startsWith('Step 2 of'),'The restored step differs.');
    assert(await page.getByRole('checkbox',{name:'Identification practice',exact:true}).isChecked(),'Practice mode was discarded.');
    assert(await page.getByRole('textbox',{name:'Identification answer',exact:true}).inputValue()===answer,'Unfinished answer was discarded.');
    assert(await page.getByRole('searchbox',{name:'Search structures'}).isDisabled(),'The unrevealed target name was exposed.');
    assert(await page.locator('.answer').count()===0,'The answer was revealed during recovery.');
  };
  await check();
  await page.getByRole('button',{name:'Next structure',exact:true}).click();await ready();
  await page.getByLabel('Import scene file', {exact:true}).setInputFiles(path);await ready();await check();
  await page.getByRole('button',{name:'Reveal and compare',exact:true}).click();
  assert((await page.locator('.answer').textContent()).includes('Left postcentral gyrus'),'Restored step feedback uses a different target.');
  await page.getByRole('combobox',{name:'Local atlas',exact:true}).selectOption(second.key);await ready();
  await page.getByRole('combobox',{name:'Local atlas',exact:true}).selectOption(first.key);await ready();
  assert((await page.locator('.answer').textContent()).includes('Left postcentral gyrus'),'Source switching lost the revealed feedback.');
  const legacy=structuredClone(original);delete legacy.state.teaching;delete legacy.state.panel;
  await page.getByLabel('Import scene file', {exact:true}).setInputFiles({name:'legacy-scene.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(legacy))});await ready();
  assert(await page.getByRole('textbox',{name:'Scene teaching notes',exact:true}).isVisible(),'Legacy scene did not return to ordinary inspection.');
  await page.getByRole('button',{name:'Learn',exact:true}).click();
  assert(await page.getByRole('combobox',{name:'Lesson',exact:true}).inputValue()==='','A stale lesson remained after ordinary scene import.');
  const invalid=structuredClone(original);invalid.state.teaching.step=999;
  await page.getByLabel('Import scene file', {exact:true}).setInputFiles({name:'invalid-lesson.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(invalid))});
  await page.getByRole('alert').filter({hasText:/teaching context/}).waitFor();
  await page.getByRole('button',{name:'Dismiss error'}).click();
  await page.getByLabel('Import scene file', {exact:true}).setInputFiles(path);await ready();await check();
  await page.screenshot({path:'output/playwright/teaching-context-restored.png'});
  assert(!failures.length,failures.join('\n'));
  return {status:'passed',checks:['lesson and step survive page reload','unrevealed practice answer survives scene recovery','portable teaching scene import','feedback survives source switching','legacy scene clears stale teaching context','unavailable lesson step rejected'],page_errors:failures};
}
