async page => {
  const failures=[];page.on('pageerror',error=>failures.push(String(error)));
  const assert=(condition,message)=>{if(!condition)throw new Error(message);};
  const ready=()=>page.waitForFunction(()=>document.querySelector('.live-status')?.textContent?.startsWith('Ready'),null,{timeout:60000});
  const catalog=await page.evaluate(async()=>(await(await fetch('/api/atlases')).json()).atlases);
  const atlas=catalog.find(a=>a.dataset_id==='mida');
  assert(!!atlas,'Serve the local MIDA model before this check.');
  const manifest=await page.evaluate(async url=>(await fetch(url)).json(),atlas.manifest_url);
  assert(manifest.representation==='label-model'&&manifest.volumes.every(v=>v.kind==='labels'),'Model declares an unavailable MRI.');
  await page.getByRole('combobox',{name:'Local atlas',exact:true}).selectOption(atlas.key);
  await ready();
  assert(await page.getByRole('combobox',{name:'MRI contrast'}).count()===0,'An MRI control is offered for a model without MRI.');
  assert(await page.getByRole('checkbox',{name:'3D MRI context'}).count()===0,'An MRI context control is offered for a model without MRI.');
  assert(await page.getByText('Categorical model sections · Original MRI not supplied',{exact:true}).isVisible(),'The representation is not clearly identified.');
  await page.getByRole('searchbox',{name:'Search structures'}).fill('pons');
  await page.getByRole('button',{name:'Pons unspecified · Brainstem',exact:true}).click();
  await ready();
  await page.getByRole('button',{name:'Isolate selected',exact:true}).click();
  await ready();
  await page.getByRole('combobox',{name:'View layout',exact:true}).selectOption('axial');
  await ready();
  await page.locator('canvas').screenshot({path:'output/playwright/model-pons-visible.png'});
  await page.getByRole('slider',{name:'Surface opacity',exact:true}).press('Home');
  await ready();
  await page.locator('canvas').screenshot({path:'output/playwright/model-pons-no-surface.png'});
  await page.getByRole('slider',{name:'Label opacity',exact:true}).press('Home');
  await ready();
  await page.locator('canvas').screenshot({path:'output/playwright/model-pons-transparent.png'});
  await page.getByRole('slider',{name:'Surface opacity',exact:true}).press('End');
  await page.getByRole('slider',{name:'Label opacity',exact:true}).press('End');
  await page.getByRole('button',{name:'Hide all',exact:true}).click();
  await ready();
  await page.locator('canvas').screenshot({path:'output/playwright/model-all-hidden.png'});
  await page.getByRole('button',{name:'Isolate selected',exact:true}).click();
  await page.getByRole('combobox',{name:'View layout',exact:true}).selectOption('quad');
  await ready();
  const target=manifest.structures.find(s=>s.id==='mida:label:14');
  const position=()=>Promise.all(['R','A','S'].map(axis=>page.getByRole('spinbutton',{name:axis+' coordinate in millimeters'}).inputValue().then(Number)));
  assert((await position()).every((v,i)=>Math.abs(v-target.target_ras_mm[i])<.011),'Model target differs from the source member voxel.');
  await page.getByRole('spinbutton',{name:'S coordinate in millimeters'}).fill(String(Number(target.target_ras_mm[2].toFixed(2))+.01));
  assert(await page.locator('.coordinate-status').textContent()==='Pons','Oblique model coordinate lookup selected a different source label.');
  await page.getByRole('button',{name:'Pons unspecified · Brainstem',exact:true}).click();
  await ready();
  await page.getByRole('checkbox',{name:'Radiological',exact:true}).uncheck();
  assert((await position()).every((v,i)=>Math.abs(v-target.target_ras_mm[i])<.011),'Display convention changed native coordinates.');
  await page.getByRole('textbox',{name:'Scene teaching notes'}).fill('Engineering browser check: categorical sections, no original MRI.');
  await page.getByRole('button',{name:'Save scene',exact:true}).click();
  await page.getByRole('button',{name:'Reset view',exact:true}).click();
  await ready();
  await page.getByRole('button',{name:'Restore saved',exact:true}).click();
  await ready();
  assert((await position()).every((v,i)=>Math.abs(v-target.target_ras_mm[i])<.011),'Model scene did not restore its target.');
  const exported=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export teaching image',exact:true}).click();
  await(await exported).saveAs('data/exports/mida/browser-validation/model-teaching.zip');
  await page.getByRole('button',{name:'Learn',exact:true}).click();
  await page.getByLabel('Lesson',{exact:true}).selectOption('NI-M004');
  await ready();
  assert(await page.getByText(/Colored model sections are categorical labels/).isVisible(),'Model lesson lacks its evidence limitation.');
  await page.getByRole('checkbox',{name:'Identification practice',exact:true}).check();
  await page.getByRole('button',{name:'Reveal and compare',exact:true}).click();
  assert((await page.locator('.answer').textContent()).includes('Midbrain'),'Model lesson target or feedback is wrong.');
  await page.getByRole('checkbox',{name:'Identification practice',exact:true}).uncheck();
  await ready();
  await page.screenshot({path:'output/playwright/model-teaching-validated.png'});
  assert(!failures.length,failures.join('\n'));
  return {status:'passed',package_version:manifest.package_version,structures:manifest.structures.length,lessons:6,
    checks:['explicit categorical model representation','no MRI controls','source target coordinates','display convention preserves physical position','saved model scene recovery','credited model export','source model lesson and identification feedback'],page_errors:failures};
}
