async page => {
  const origin = new URL(page.url()).origin;
  const assert = (value, message) => { if (!value) throw Error(message); };
  const errors = [], retiredRequests = [], checks = [];
  page.setDefaultTimeout(120000); page.setDefaultNavigationTimeout(120000);
  const onError = error => errors.push(String(error));
  const onRequest = request => { if (/\/api\/workspace\/(?:teaching|courses|content)(?:\/|$)|\/lessons\.json(?:\?|$)/.test(request.url())) retiredRequests.push(request.url()); };
  page.on('pageerror', onError); page.on('request', onRequest);
  const catalog = await (await page.request.get(origin + '/api/workspace/browse')).json();
  const workspace = await (await page.request.get(origin + '/api/workspace')).json();
  const output = workspace.data_root + '/exports/release-simplification-validation';
  const latest = id => catalog.packages.filter(item => item.dataset_id === id && item.status === 'available').sort((a,b) => b.created_utc.localeCompare(a.created_utc))[0];
  const primary = latest('cerebra'), comparison = latest('cit168_native'), model = latest('bigbrain_hippocampus');
  assert(primary && comparison && model, 'Serve CerebrA, CIT168 and BigBrain hippocampal surfaces.');
  const ready = async (scope = page) => {
    await scope.locator('.live-status,.model-status').filter({hasText:/^(Ready|Scene saved|Saved scene restored|Scene file restored|Image export prepared|Model scene saved|Source-bound|Model image)/}).first().waitFor();
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    assert(await page.getByRole('alert').count() === 0, 'A viewer error is visible.');
  };
  const coordinates = scope => scope.locator('.coordinate-bar input').evaluateAll(items => items.map(item => item.value));
  const same = (a,b) => JSON.stringify(a) === JSON.stringify(b);
  const download = async (name, file) => {
    const event = page.waitForEvent('download');
    await page.getByRole('button', {name,exact:true}).click();
    const result = await event; await result.saveAs(file); return result.suggestedFilename();
  };
  try {
    await page.goto(origin + '/?view=teaching&course=retained-historical-course');
    await page.getByRole('heading',{name:'Browse anatomy',exact:true}).waitFor();
    await page.waitForURL(origin + '/?view=anatomy');
    assert(!await page.getByRole('button',{name:'Teaching library',exact:true}).count(), 'Retired navigation remains.');
    checks.push('Legacy teaching links return to anatomy');
    await page.goto(origin + '/?view=workspace&dataset=cerebra');
    await page.getByRole('button',{name:'Back to dataset',exact:true}).waitFor();
    assert(!await page.getByRole('button',{name:/prepare.*(?:teaching|course|notebook)/i}).count(), 'Retired job controls remain.');
    await page.getByRole('button',{name:'Back to dataset',exact:true}).click();
    assert(new URL(page.url()).searchParams.get('dataset') === 'cerebra', 'Dataset navigation was lost.');
    checks.push('Dataset management returns to its dataset');
    await page.goto(origin + '/?view=atlas&atlas=' + primary.key + '&group=cerebral-cortex'); await ready();
    const original = await coordinates(page);
    assert(await page.getByRole('button',{name:'2D background',exact:true}).getAttribute('aria-pressed') === 'true','2D background did not start enabled.');
    assert(await page.getByRole('button',{name:'3D background',exact:true}).getAttribute('aria-pressed') === 'false','3D background did not start disabled.');
    await page.getByRole('button',{name:'2D background',exact:true}).click(); await ready();
    await page.getByRole('button',{name:'3D background',exact:true}).click(); await ready();
    assert(same(original,await coordinates(page)),'Background changes moved the native cursor.');
    await page.getByRole('button',{name:'2D background',exact:true}).click();
    await page.getByRole('button',{name:'3D background',exact:true}).click(); await ready();
    checks.push('Regional 2D and 3D backgrounds remain independent');
    await page.locator('.anatomy-display-details > summary').click();
    await page.getByRole('checkbox',{name:'Show 3D cursor',exact:true}).uncheck();
    await page.locator('.surface-cutaway-controls > summary').click();
    await page.getByRole('button',{name:'Cut visible surfaces at cursor',exact:true}).click(); await ready();
    assert(same(original,await coordinates(page)),'Cutaway changed the section coordinates.');
    await page.getByRole('button',{name:'Save scene',exact:true}).click();
    await page.getByRole('button',{name:'Restore saved',exact:true}).waitFor({state:'visible'}); await ready();
    await page.getByRole('checkbox',{name:'Show 3D cursor',exact:true}).check();
    await page.getByRole('button',{name:'Reset view',exact:true}).click(); await ready();
    await page.getByRole('button',{name:'Restore saved',exact:true}).click(); await ready();
    assert(!await page.getByRole('checkbox',{name:'Show 3D cursor',exact:true}).isChecked(),'Saving lost cursor visibility.');
    assert(await page.locator('.surface-cutaway-controls input[type=number]').count() === 1,'Saving lost the cutaway.');
    const imageScene = 'output/playwright/release-image-scene.json';
    await download('Export scene', imageScene);
    await page.getByRole('button',{name:'Reset view',exact:true}).click(); await ready();
    await page.getByLabel('Import scene file',{exact:true}).setInputFiles(imageScene); await ready();
    assert(!await page.getByRole('checkbox',{name:'Show 3D cursor',exact:true}).isChecked(),'Scene import lost cursor visibility.');
    assert(same(original,await coordinates(page)),'Scene import moved the cursor.');
    await download('Export image', output + '/image-export.zip');
    checks.push('Image scenes save, restore, export and import native display state and credited images');
    await page.locator('.anatomy-display-details > summary').click();
    await page.getByRole('button',{name:'Expand viewer',exact:true}).click();
    await page.getByRole('dialog',{name:'Expanded atlas viewer',exact:true}).waitFor();
    await page.keyboard.press('Escape');
    assert(!await page.getByRole('dialog').count(),'Escape did not leave the expanded view.');
    assert(same(original,await coordinates(page)),'Expanded mode moved the cursor.');
    await page.getByRole('checkbox',{name:'Compare sources',exact:true}).check();
    await page.getByRole('combobox',{name:'Compare with',exact:true}).selectOption(comparison.key);
    const left=page.getByRole('region',{name:'Primary atlas workspace',exact:true}),right=page.getByRole('region',{name:'Comparison atlas workspace',exact:true});
    await ready(right);
    const second = await coordinates(right);
    await right.getByRole('combobox',{name:'View layout',exact:true}).selectOption('coronal'); await ready(right);
    await right.getByRole('button',{name:'Magnify at cursor',exact:true}).click(); await ready(right);
    assert(same(original,await coordinates(left)) && same(second,await coordinates(right)), 'Comparison linked independent native coordinates.');
    await page.screenshot({path:'output/playwright/release-comparison.png',fullPage:true});
    await page.getByRole('checkbox',{name:'Compare sources',exact:true}).uncheck(); await ready();
    assert(same(original,await coordinates(page)), 'Closing comparison lost the primary view.');
    checks.push('Independent comparison and expanded view preserve primary state');
    await page.setViewportSize({width:820,height:1000});
    await page.getByRole('button',{name:'Structure library',exact:true}).click();
    assert(await page.getByRole('searchbox',{name:'Search structures',exact:true}).isVisible(), 'Narrow structure drawer is inaccessible.');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), 'Narrow layout overflows the page.');
    await page.getByRole('button',{name:'Close structure library',exact:true}).click();
    await page.screenshot({path:'output/playwright/release-narrow.png',fullPage:true});
    await page.setViewportSize({width:1440,height:1000});
    checks.push('Narrow layout keeps anatomy controls accessible');
    await page.goto(origin + '/?view=atlas&atlas=' + model.key); await ready();
    await page.locator('.model-display-details > summary').click();
    await page.locator('.model-cutaway > summary').click();
    await page.getByRole('button',{name:'Cut selected at cursor',exact:true}).click(); await ready();
    const modelPoint = await page.locator('.model-coordinate-bar').textContent();
    await page.getByRole('button',{name:'Save scene',exact:true}).click(); await ready();
    await page.getByRole('button',{name:'Remove cutaway',exact:true}).click(); await ready();
    await page.getByRole('button',{name:'Restore saved',exact:true}).click(); await ready();
    assert(await page.getByRole('button',{name:'Remove cutaway',exact:true}).count() === 1,'Model scene lost its cutaway.');
    const modelScene = 'output/playwright/release-model-scene.json';
    await download('Export scene', modelScene);
    await page.getByRole('button',{name:'Remove cutaway',exact:true}).click(); await ready();
    await page.getByLabel('Import model scene file',{exact:true}).setInputFiles(modelScene); await ready();
    assert(await page.getByRole('button',{name:'Remove cutaway',exact:true}).count() === 1,'Model scene import lost its cutaway.');
    assert(await page.locator('.model-coordinate-bar').textContent() === modelPoint,'Model scene import changed native coordinates.');
    await download('Export image', output + '/model-export.zip');
    await page.screenshot({path:'output/playwright/release-model-controls.png',fullPage:true});
    checks.push('Source-model scenes and cutaways survive save, restore, import and credited export');
    assert(!errors.length, errors.join('\n'));
    assert(!retiredRequests.length, 'The browser requested retired learning resources.');
    return {status:'passed',checks,page_errors:errors,retired_requests:retiredRequests};
  } finally {page.off('pageerror',onError);page.off('request',onRequest);}
}
