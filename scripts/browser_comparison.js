async page => {
  const failures=[];page.on('pageerror',error=>failures.push(String(error)));
  await page.reload();
  const primary=page.getByRole('region',{name:'Primary atlas workspace',exact:true});
  const comparison=page.getByRole('region',{name:'Comparison atlas workspace',exact:true});
  const ready=scope=>scope.locator('.live-status').filter({hasText:/^Ready/}).waitFor({timeout:45000});
  const position=scope=>Promise.all(['R','A','S'].map(axis=>scope.getByRole('spinbutton',{name:axis+' coordinate in millimeters'}).inputValue().then(Number)));
  const assert=(condition,message)=>{if(!condition)throw new Error(message)};
  const catalog=await page.evaluate(async()=>(await(await fetch('/api/atlases')).json()).atlases);
  const first=catalog.find(a=>a.dataset_id==='spl_nac'),second=catalog.find(a=>a.dataset_id==='cerebra');
  await page.getByRole('combobox',{name:'Local atlas',exact:true}).selectOption(first.key);
  await ready(primary);
  await page.getByRole('checkbox',{name:'Compare native spaces',exact:true}).check();
  await page.getByRole('combobox',{name:'Compare with',exact:true}).selectOption(second.key);
  await ready(comparison);
  const originalSecond=await position(comparison);
  await primary.getByRole('button',{name:'Structure library',exact:true}).click();
  await primary.getByRole('searchbox',{name:'Search structures'}).fill('left putamen');
  await primary.getByRole('button',{name:'Left putamen left · Deep structures',exact:true}).click();
  await ready(primary);
  assert(JSON.stringify(await position(comparison))===JSON.stringify(originalSecond),'Primary selection changed the other native-space cursor.');
  await primary.getByRole('button',{name:'Learning tools',exact:true}).click();
  await primary.getByRole('textbox',{name:'Scene teaching notes'}).fill('Primary native-space comparison note.');
  await primary.getByRole('button',{name:'Close learning tools',exact:true}).click();
  await comparison.getByRole('button',{name:'Learning tools',exact:true}).click();
  await comparison.getByRole('textbox',{name:'Scene teaching notes'}).fill('Independent secondary native-space note.');
  await comparison.getByRole('button',{name:'Close learning tools',exact:true}).click();
  await comparison.getByRole('checkbox',{name:'Radiological',exact:true}).uncheck();
  await comparison.getByRole('combobox',{name:'MRI contrast'}).selectOption('t2');
  await ready(comparison);
  assert(await primary.getByRole('checkbox',{name:'Radiological',exact:true}).isChecked(),'Display convention leaked between panels.');
  assert(await primary.getByRole('combobox',{name:'MRI contrast'}).inputValue()==='t1','Contrast selection leaked between panels.');
  await primary.getByRole('spinbutton',{name:'R coordinate in millimeters'}).fill('300');
  await page.getByRole('checkbox',{name:'Compare native spaces',exact:true}).uncheck();
  assert(await primary.getByRole('spinbutton',{name:'R coordinate in millimeters'}).inputValue()==='300','Closing comparison reset the primary cursor.');
  assert(await primary.getByRole('textbox',{name:'Scene teaching notes'}).inputValue()==='Primary native-space comparison note.','Closing comparison discarded primary notes.');
  await page.getByRole('checkbox',{name:'Compare native spaces',exact:true}).check();
  await ready(comparison);
  assert(await comparison.getByRole('combobox',{name:'MRI contrast'}).inputValue()==='t2','Reopening comparison lost its view state.');
  assert(JSON.stringify(await position(comparison))===JSON.stringify(originalSecond),'Reopening comparison changed the independent cursor.');
  await comparison.getByRole('button',{name:'Learning tools',exact:true}).click();
  assert(await comparison.getByRole('textbox',{name:'Scene teaching notes'}).inputValue()==='Independent secondary native-space note.','Reopening comparison discarded its notes.');
  await comparison.getByRole('button',{name:'Close learning tools',exact:true}).click();
  // The same package can be inspected from two independent views as well.
  await page.getByRole('combobox',{name:'Local atlas',exact:true}).selectOption(second.key);
  await ready(primary);
  await primary.getByRole('button',{name:'Learning tools',exact:true}).click();
  await primary.getByRole('textbox',{name:'Scene teaching notes'}).fill('Same package, independent primary view.');
  await primary.getByRole('button',{name:'Close learning tools',exact:true}).click();
  await primary.getByRole('button',{name:'Save scene',exact:true}).click();
  await comparison.getByRole('button',{name:'Save scene',exact:true}).click();
  const scenes=await page.evaluate(key=>[JSON.parse(localStorage.getItem('neuroimage:scene:'+key)),JSON.parse(localStorage.getItem('neuroimage:scene:comparison:'+key))],second.key);
  assert(scenes[0].state.note==='Same package, independent primary view.' && scenes[1].state.note==='Independent secondary native-space note.','The two saved views overwrote each other.');
  await page.getByRole('combobox',{name:'Local atlas',exact:true}).selectOption(first.key);
  await ready(primary);
  assert(await primary.getByRole('spinbutton',{name:'R coordinate in millimeters'}).inputValue()==='300','Returning to a package lost its session cursor.');
  await primary.getByRole('button',{name:'Reset view',exact:true}).click();
  await ready(primary);
  await page.screenshot({path:'output/playwright/native-comparison-validated.png'});
  assert(!failures.length,failures.join('\n'));
  return {status:'passed',checks:['independent native coordinates','independent contrast and display convention','notes and view survive closing comparison','workspace state survives atlas switching','separate saved scenes for two views of one package'],page_errors:failures};
}
