async page => {
  const failures = [];
  const externalRequests = [];
  const localOrigin = new URL(page.url()).origin;
  await page.route('**/*', route => {
    if (new URL(route.request().url()).origin === localOrigin) return route.continue();
    externalRequests.push(route.request().url());
    return route.abort();
  });
  await page.reload();
  await page.waitForSelector('button.primary:not([disabled])');
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  page.on('pageerror', error => failures.push(String(error)));
  const catalog = await page.evaluate(async () => (await (await fetch('/api/atlases')).json()).atlases);
  const spl = catalog.find(a => a.dataset_id === 'spl_nac');
  const cerebra = catalog.find(a => a.dataset_id === 'cerebra');
  assert(spl && cerebra, 'This local browser check requires the SPL/NAC and CerebrA packages.');
  const ready = async () => {
    await page.waitForFunction(() => !document.querySelector('button.primary')?.disabled && document.querySelector('.live-status')?.textContent?.startsWith('Ready'), null, {timeout: 45000});
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  };
  await page.getByRole('combobox', {name: 'Local atlas', exact: true}).selectOption(spl.key);
  await ready();
  const manifest = await page.evaluate(async url => (await fetch(url)).json(), spl.manifest_url);
  const target = manifest.structures.find(s => s.name === 'Left putamen');
  assert(target, 'The source package must contain the chosen test structure.');
  await page.getByRole('button', {name: 'Inspect', exact: true}).click();
  await page.getByRole('searchbox', {name: 'Search structures'}).fill('left putamen');
  await page.getByRole('button', {name: 'Left putamen left · Deep structures', exact: true}).click();
  await ready();
  const positions = async () => Promise.all(['R','A','S'].map(axis => page.getByRole('spinbutton', {name: axis + ' coordinate in millimeters'}).inputValue().then(Number)));
  let xyz = await positions();
  assert(xyz.every((value, i) => Math.abs(value - target.target_ras_mm[i]) < .02), 'List selection did not use the source target coordinates.');
  await page.getByRole('checkbox', {name: 'Radiological', exact: true}).uncheck();
  await ready();
  xyz = await positions();
  assert(xyz.every((value, i) => Math.abs(value - target.target_ras_mm[i]) < .02), 'Changing display convention changed the world location.');
  await page.getByRole('combobox', {name: 'MRI contrast'}).selectOption('t2');
  await ready();
  const teachingNote = 'Engineering validation: preserve this source-bound teaching scene. ' + new Date().toISOString();
  await page.getByRole('textbox', {name: 'Scene teaching notes'}).fill(teachingNote);
  await page.getByRole('textbox', {name: 'New location annotation'}).fill('Source label target used for engineering correspondence check.');
  await page.getByRole('button', {name: 'Add marker at cursor', exact: true}).click();
  await ready();
  await page.getByRole('button', {name: 'Save scene', exact: true}).click();
  await page.waitForFunction(([key, note]) => JSON.parse(localStorage.getItem(key) || 'null')?.state?.note === note, ['neuroimage:scene:' + spl.key, teachingNote]);
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem('neuroimage:scene:' + key)), spl.key);
  assert(saved.state.selected === target.id && saved.state.annotations.length === 1 && !saved.state.radiological && saved.state.background === 't2', 'Saved scene omitted display or teaching state.');
  await page.getByRole('button', {name: 'Reset view', exact: true}).click();
  await ready();
  assert((await page.getByRole('textbox', {name:'Scene teaching notes'}).inputValue()).includes('Engineering validation'), 'Reset view erased teaching notes.');
  await page.getByRole('button', {name: 'Restore saved', exact: true}).click();
  await ready();
  xyz = await positions();
  assert(xyz.every((value, i) => Math.abs(value - saved.state.position[i]) < .02), 'Scene restoration changed the physical location.');
  assert(await page.getByRole('combobox', {name:'MRI contrast'}).inputValue() === 't2', 'Scene restoration omitted the MRI contrast.');
  const sceneDownload = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Export scene', exact: true}).click();
  await (await sceneDownload).saveAs('data/exports/spl_nac/browser-validation/scene.json');
  const imageDownload = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Export teaching image', exact: true}).click();
  await (await imageDownload).saveAs('data/exports/spl_nac/browser-validation/teaching-export.zip');
  const wrong = {...saved, space_id: 'unrelated-native-space'};
  await page.getByLabel('Import scene file', {exact:true}).setInputFiles({name:'mismatched-scene.json', mimeType:'application/json', buffer:Buffer.from(JSON.stringify(wrong))});
  const alert = await page.getByRole('alert').textContent();
  assert(alert.includes('different atlas version or native space'), 'Cross-space scene was not rejected.');
  await page.getByRole('button', {name:'Dismiss error'}).click();
  await page.getByLabel('Import scene file', {exact:true}).setInputFiles('data/exports/spl_nac/browser-validation/scene.json');
  await ready();
  await page.getByRole('button', {name:'Learn',exact:true}).click();
  await page.getByRole('combobox', {name:'Lesson',exact:true}).selectOption('NI-L004');
  await ready();
  await page.getByRole('checkbox', {name:'Identification practice'}).check();
  assert(await page.getByRole('searchbox', {name:'Search structures'}).isDisabled(), 'Identification mode leaked the structure browser.');
  await page.getByRole('textbox', {name:'Identification answer'}).fill('Left precentral gyrus');
  await page.getByRole('button', {name:'Reveal and compare'}).click();
  assert((await page.locator('.answer').textContent()).includes('Left precentral gyrus'), 'Identification feedback did not use the source label.');
  await page.screenshot({path:'output/playwright/spl-teaching-validated.png'});
  await page.getByRole('combobox', {name:'Local atlas',exact:true}).selectOption(cerebra.key);
  await ready();
  assert((await page.getByRole('heading', {level:1}).textContent()).includes('2009c symmetric'), 'Second package was not opened in its own native space.');
  for (const contrast of ['t2', 't1', 't2', 't1']) await page.getByRole('combobox', {name:'MRI contrast'}).selectOption(contrast);
  await ready();
  assert(await page.getByRole('combobox', {name:'MRI contrast'}).inputValue() === 't1', 'Rapid image switching did not settle on the requested contrast.');
  assert((await positions())[0] < 0, 'Left structure has the wrong RAS side in the second atlas.');
  await page.screenshot({path:'output/playwright/cerebra-validated.png'});
  assert(failures.length === 0, failures.join('\n'));
  assert(externalRequests.length === 0, 'Offline workflow attempted an external request: ' + externalRequests.join(', '));
  return {status:'passed', checks:['source target selection', 'display convention preserves coordinates', 'T1/T2 switch', 'notes and coordinate annotation', 'browser scene save/restore', 'scene file export/import', 'credited image export', 'cross-space rejection', 'lesson and identification feedback', 'second native-space package', 'rapid image switching', 'offline requests restricted to the local service'], atlas_versions:[spl.package_version,cerebra.package_version], page_errors:failures, external_requests:externalRequests};
}
