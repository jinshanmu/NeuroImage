async page => {
  const errors = [], warnings = [];
  page.on('pageerror', error => errors.push(String(error)));
  page.on('console', message => { if (message.type() === 'warning' && /GL_INVALID/.test(message.text())) warnings.push(message.text()); });
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const ready = () => page.waitForFunction(() => document.querySelector('.live-status')?.textContent?.startsWith('Ready'), null, { timeout: 60000 });
  const frame = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.reload(); await ready();
  const catalog = await page.evaluate(async () => (await (await fetch('/api/atlases')).json()).atlases);
  const packages = [];
  for (const dataset of ['spl_nac', 'mida']) {
    const atlas = catalog.find(a => a.dataset_id === dataset);
    assert(atlas, 'Serve SPL/NAC and MIDA before this marker check.');
    await page.getByLabel('Local atlas', { exact: true }).selectOption(atlas.key); await ready();
    const manifest = await page.evaluate(async url => (await fetch(url)).json(), atlas.manifest_url);
    const target = manifest.structures.find(s => s.name === (dataset === 'spl_nac' ? 'Left putamen' : 'Pons'));
    await page.locator('button[title="' + target.id + '"]').click(); await ready();
    const position = () => Promise.all(['R', 'A', 'S'].map(axis => page.getByLabel(axis + ' coordinate in millimeters').inputValue().then(Number)));
    const before = await position(), text = 'Engineering teaching marker: inspect this source target.';
    await page.getByLabel('New location annotation').fill(text);
    await page.getByRole('button', { name: 'Add marker at cursor', exact: true }).click();
    await ready(); await frame();
    await page.locator('canvas').screenshot({ path: 'output/playwright/markers-' + dataset + '-quad.png' });
    await page.getByLabel('Show teaching markers').uncheck(); await ready(); await frame();
    await page.locator('canvas').screenshot({ path: 'output/playwright/markers-' + dataset + '-quad-hidden.png' });
    await page.getByLabel('Show teaching markers').check();
    await page.getByLabel('View layout', { exact: true }).selectOption('axial'); await ready(); await frame();
    await page.locator('canvas').screenshot({ path: 'output/playwright/markers-' + dataset + '-axial.png' });
    await page.getByLabel('S coordinate in millimeters').fill(String(before[2] + 1)); await ready(); await frame();
    await page.locator('canvas').screenshot({ path: 'output/playwright/markers-' + dataset + '-off-plane.png' });
    await page.getByLabel('Show teaching markers').uncheck(); await ready(); await frame();
    await page.locator('canvas').screenshot({ path: 'output/playwright/markers-' + dataset + '-off-plane-hidden.png' });
    await page.getByLabel('Show teaching markers').check();
    await page.locator('.annotation button').first().click(); await ready(); await frame();
    assert((await position()).every((v, i) => Math.abs(v - before[i]) < .011), 'Marker navigation changed its saved physical position.');
    assert(await page.locator('.coordinate-status').textContent() === target.name, 'Marker navigation lost its associated source structure.');
    await page.getByLabel('Radiological', { exact: true }).uncheck(); await ready(); await frame();
    await page.locator('canvas').screenshot({ path: 'output/playwright/markers-' + dataset + '-neurological.png' });
    assert((await position()).every((v, i) => Math.abs(v - before[i]) < .011), 'Display convention changed marker coordinates.');
    await page.getByRole('button', { name: 'Save scene', exact: true }).click();
    await page.getByLabel('Show teaching markers').uncheck();
    await page.getByRole('button', { name: 'Restore saved', exact: true }).click(); await ready();
    assert(await page.getByLabel('Show teaching markers').isChecked(), 'Marker visibility did not restore with the scene.');
    await page.getByLabel('View layout', { exact: true }).selectOption('quad'); await ready();
    const output = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export teaching image', exact: true }).click();
    await (await output).saveAs('data/exports/' + dataset + '/browser-validation/teaching-markers.zip');
    await page.getByRole('button', { name: 'Learn', exact: true }).click();
    await page.getByLabel('Lesson', { exact: true }).selectOption(dataset === 'spl_nac' ? 'NI-L004' : 'NI-M004');
    await ready();
    await page.getByLabel('Identification practice', { exact: true }).check(); await ready();
    const practice = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export teaching image', exact: true }).click();
    await (await practice).saveAs('data/exports/' + dataset + '/browser-validation/unrevealed-practice.zip');
    packages.push({ dataset, package_version: manifest.package_version, marker_position_ras_mm: before, source_structure: target.id });
  }
  assert(!errors.length && !warnings.length, 'Marker rendering produced a page or WebGL error.');
  return { status: 'passed', packages, checks: ['native and oblique source positions', 'four-view marker rendering', 'off-plane marker hiding', 'display convention preserves coordinates', 'marker scene recovery', 'numbered export and full-text appendix', 'unrevealed practice export'], page_errors: errors, webgl_warnings: warnings };
}
